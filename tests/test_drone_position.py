import pytest
from pydantic import ValidationError

from main import DronePosition

def test_valid_drone_position():

    drone_data = {
        "uid": "uav_01",
        "callsign": "Drone Alpha",
        "aircraft_type": "a-f-A",
        "position": {
            "latitude": 45.0,
            "longitude": -75.0,
            "altitude_hae_m": 100.0,
            "ce_m": 5.0,
            "le_m": 8.0,
        },
        "motion": {
            "course_deg": 90.0,
            "speed_mps": 12.0,
            "climb_rate_mps": 0.0,
        },
        "status": {
            "battery_percent": 75.0,
            #"gps_fix": True,
        },
        "details": {
            "remarks": "Position generated by drone simulator"
        }
    }

    drone = DronePosition(**drone_data)
    assert drone.uid == "uav_01"
    assert drone.callsign == "Drone Alpha"
    assert drone.aircraft_type == "a-f-A"
    assert drone.position.latitude == 45.0
    assert drone.position.longitude == -75.0
    assert drone.position.altitude_hae_m == 100.0
    assert drone.position.ce_m == 5.0
    assert drone.position.le_m == 8.0
    assert drone.motion.course_deg == 90.0
    assert drone.motion.speed_mps == 12.0
    assert drone.motion.climb_rate_mps == 0.0
    assert drone.status.battery_percent == 75.0
    # assert drone.status.gps_fix is True
    assert drone.details.remarks == "Position generated by drone simulator"
    

