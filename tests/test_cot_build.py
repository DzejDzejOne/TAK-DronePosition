from datetime import datetime, timezone
from types import SimpleNamespace
import xml.etree.ElementTree as ET

from cot_build import build_cot, iso_time
from main import DronePosition

drone_data = {
    "uid": "uav-01",
    "callsign": "Drone Mu",
    "aircraft_type": "a-f-A",
    "position": {
        "latitude": 45.0,
        "longitude": -75.0,
        "altitude_hae_m": 100.0,
        "ce_m": 5.0,
        "le_m": 8.0,
    },
    "motion": {
        "course_deg": 90.0,
        "speed_mps": 12.0,
        "climb_rate_mps": 0.0,
    },
    "status": {
        "battery_percent": 75.0,
        "gps_fix": True,
    },
    "details": {
        "remarks": "Position generated by drone simulator"
    }
}

def test_iso_time():
    dt = datetime(
        2026,
        9,
        30,
        12,
        49,
        50,
        123000,
        tzinfo=timezone.utc
    )

    assert iso_time(dt) == "2026-09-30T12:49:50.123Z"

def test_build_cot_return_valid_xml():
    
    drone = DronePosition(**drone_data)
    
    cot = build_cot(drone)

    xml = ET.fromstring(cot)

    assert xml.tag == "event"
    assert xml.attrib["version"] == "2.0"
    assert xml.attrib["uid"] == "uav-01"
    assert xml.attrib["type"] == "a-f-A"
    assert xml.attrib["how"] == "h-e"

def test_build_cot_create_correct_point():

    drone = DronePosition(**drone_data)

    cot = build_cot(drone)

    xml = ET.fromstring(cot)

    point = xml.find("point")

    assert point is not None

    assert point.attrib["lat"] == "45.0"
    assert point.attrib["lon"] == "-75.0"
    assert point.attrib["hae"] == "100.0"
    assert point.attrib["ce"] == "5.0"
    assert point.attrib["le"] == "8.0"

def test_build_cot_create_correct_track():

    drone = DronePosition(**drone_data)
    
    cot = build_cot(drone)

    xml = ET.fromstring(cot)

    track = xml.find("track")

    assert track is not None

    assert track.attrib["course"] == "90.0"
    assert track.attrib["speed"] == "12.0"
    assert track.attrib["climb_rate"] == "0.0"

def test_build_cot_create_correct_status():

    drone = DronePosition(**drone_data)

