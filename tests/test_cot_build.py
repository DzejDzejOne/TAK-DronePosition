from datetime import datetime, timezone
from types import SimpleNamespace
import xml.etree.ElementTree as ET

from cot_build import build_cot, iso_time

def test_iso_time():
    dt = datetime(
        2026,
        9,
        30,
        12,
        49,
        50,
        123000,
        tzinfo=timezone.utc
    )

    assert iso_time(dt) == "2026-09-30T12:49:50.123Z"

